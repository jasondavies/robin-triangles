#!/usr/bin/env python3
"""Write paper/claims.tex (one \\newcommand per claim) from claims.json.  scripts/verify.py fails if the
committed paper/claims.tex differs from what this script produces."""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def tex(v):
    if v.isdigit() and len(v) > 4:                     # 445704 -> 445\,704
        return r'\,'.join(v[max(0, i - 3):i] for i in range(len(v), 0, -3)[::-1])
    if 'e-' in v:
        m, e = v.split('e-')
        return r'%s\cdot10^{-%s}' % (m, e.lstrip('0')) if m != '1' else r'10^{-%s}' % e.lstrip('0')
    return v


def render():
    c = json.loads((ROOT / 'claims.json').read_text())
    lines = ['% Generated by scripts/make_claims_tex.py from claims.json -- do not edit by hand.']
    for k, v in c.items():
        if k.startswith('_') or not isinstance(v, str):
            continue
        lines.append(r'\newcommand{\cl%s}{%s}' % (k, tex(v)))
    for row in c['tableC']:
        cells = [row['beta'], row['M'], row['theta']] + ['$%s$' % tex(row[k]) for k in ('gamma', 'Lam', 'rhs')]
        lines.append(r'\newcommand{\clTCrow%s}{%s\\}' % (row['key'], ' & '.join(cells)))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = ROOT / 'paper' / 'claims.tex'
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        ok = out.exists() and out.read_text() == render()
        print('claims.tex in sync with claims.json:', ok)
        sys.exit(0 if ok else 1)
    out.write_text(render())
    print('wrote', out.relative_to(ROOT))
