#!/usr/bin/env python3
"""The six-wave cell certificate on 6/5 <= beta <= 3 (an independent cross-check; not needed for the proof).

The certificate files (about 100 MB of JSON) are not committed. data/cells_summary.json records the
generation parameters, the counts and a content hash (SHA-256 of the canonical JSON without the timing
field) of every file of the run reported in the paper.

  .venv/bin/python scripts/cells.py generate [DIR] [-j N]   # regenerate the files into DIR (several CPU hours)
  .venv/bin/python scripts/cells.py replay   [DIR]          # re-check every cell in Arb (about 25 minutes)
  .venv/bin/python scripts/cells.py summary  [DIR]          # (maintainer) rewrite data/cells_summary.json

DIR defaults to $CELLS_DIR or ./cells (git-ignored).  `replay` is what `scripts/verify.py --cells` runs; it
writes verification/cells.json.  It re-checks every stored cell from its stored trial coefficients and the
contiguity of all intervals, compares the counts with data/cells_summary.json and reports whether the content
hashes agree with the recorded run (regeneration with the pinned versions is expected to reproduce them, but
the replay does not depend on it)."""
import argparse, hashlib, json, os, subprocess, sys, time
from fractions import Fraction as Fr
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CODE = ROOT / 'code'
SUMMARY = ROOT / 'data' / 'cells_summary.json'
PY = sys.executable

LOCAL = [('L1', '671/500', '2'), ('L2', '2', '27/10'), ('L3', '27/10', '341/100')]


def sha(p):
    """SHA-256 of the certificate content: the canonical JSON without the run-time field 'seconds'."""
    d = json.loads(Path(p).read_text())
    d.pop('seconds', None)
    return hashlib.sha256(json.dumps(d, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def env(d):
    return dict(os.environ, CELLS_DIR=str(d), OMP_NUM_THREADS='1', OPENBLAS_NUM_THREADS='1', MKL_NUM_THREADS='1')


def far_files(d):
    return sorted(Path(d).glob('far_[FG]*.json'), key=lambda p: (p.name[4], int(p.stem[5:])))


def summary(d):
    d = Path(d); out = dict(_comment='Six-wave cell certificate of the paper (Section 6); files are regenerated by '
                            'scripts/cells.py generate and replayed by scripts/cells.py replay.',
                            local=[], far=[], files={})
    for tag, lo, hi in LOCAL:
        loc = json.loads((d / f'local_{tag}.json').read_text()); near = json.loads((d / f'near_{tag}.json').read_text())
        assert loc['Mlo'] == lo and loc['Mhi'] == hi and loc['complete']
        rs = [Fr(x[2]) for x in loc['intervals']]; Rs = [Fr(x[3]) for x in near['intervals']]
        out['local'].append(dict(tag=tag, Mlo=lo, Mhi=hi, local_intervals=len(loc['intervals']),
                                 near_intervals=len(near['intervals']),
                                 r_min=str(min(rs)), r_max=str(max(rs)), R_min=str(min(Rs)), R_max=str(max(Rs))))
        for f in (f'local_{tag}.json', f'near_{tag}.json'):
            out['files'][f] = sha(d / f)
    for f in far_files(d):
        x = json.loads(f.read_text())
        assert x['ok'] and not x['fails']
        out['far'].append(dict(tag=f.stem[4:], BLO=x['BLO'], BHI=x['BHI'], a_max=x['a_max'], w0='0.01', cells=x['ncells']))
        out['files'][f.name] = sha(f)
    out['totals'] = dict(local_intervals=sum(x['local_intervals'] for x in out['local']),
                         near_intervals=sum(x['near_intervals'] for x in out['local']),
                         far_files=len(out['far']), far_cells=sum(x['cells'] for x in out['far']),
                         r_min=str(min(Fr(x['r_min']) for x in out['local'])), r_max=str(max(Fr(x['r_max']) for x in out['local'])),
                         R_min=str(min(Fr(x['R_min']) for x in out['local'])), R_max=str(max(Fr(x['R_max']) for x in out['local'])))
    return out


def run_jobs(cmds, d, jobs):
    """run (cmd, logname) pairs with at most `jobs` concurrent processes"""
    running = []
    for cmd, log in cmds:
        while len(running) >= jobs:
            for p in running:
                if p.poll() is not None:
                    running.remove(p)
                    if p.returncode: raise SystemExit('job failed: %s' % p.args)
                    break
            else:
                time.sleep(5)
        print('start', ' '.join(cmd[1:]), flush=True)
        running.append(subprocess.Popen(cmd, cwd=CODE, env=env(d), stdout=open(Path(d) / log, 'w'), stderr=subprocess.STDOUT))
    for p in running:
        if p.wait(): raise SystemExit('job failed: %s' % p.args)


def generate(d, jobs):
    d = Path(d); d.mkdir(parents=True, exist_ok=True)
    s = json.loads(SUMMARY.read_text())
    run_jobs([([PY, '-u', 'cover_local.py', lo, hi, tag], f'local_{tag}.log') for tag, lo, hi in LOCAL], d, jobs)
    run_jobs([([PY, '-u', 'near_cover.py', tag], f'near_{tag}.log') for tag, _, _ in LOCAL], d, jobs)
    run_jobs([([PY, '-u', 'far_driver.py', x['BLO'], x['BHI'], x['tag'], x['w0'], x['a_max']], f"far_{x['tag']}.log")
              for x in s['far']], d, jobs)
    same = {f: (d / f).exists() and sha(d / f) == h for f, h in s['files'].items()}
    print('files identical to the recorded run: %d of %d' % (sum(same.values()), len(same)))


def replay(d):
    d = Path(d); s = json.loads(SUMMARY.read_text()); t0 = time.time()
    missing = [f for f in s['files'] if not (d / f).exists()]
    if missing:
        raise SystemExit('missing certificate files in %s (run scripts/cells.py generate first): %s' % (d, missing[:5]))
    res = dict(local=[], far=[], hashes_match={f: sha(d / f) == h for f, h in s['files'].items()})
    for tag, _, _ in LOCAL:
        subprocess.run([PY, 'verify_local_near.py', tag], cwd=CODE, env=env(d), check=True)
        res['local'].append(json.loads((ROOT / 'verification' / f'cells_localnear_{tag}.json').read_text()))
    for x in s['far']:
        subprocess.run([PY, 'verify_far.py', str(d / f"far_{x['tag']}.json")], cwd=CODE, env=env(d), check=True)
        res['far'].append(json.loads((ROOT / 'verification' / f"cells_far_far_{x['tag']}.json").read_text()))
    # coverage: M-intervals contiguous across tags and around [M(6/5), M(3)]; beta-intervals contiguous on [6/5, 3]
    sys.path.insert(0, str(CODE))
    from flint import arb, fmpq
    from equi import beta_of
    Ms = [(Fr(lo), Fr(hi)) for _, lo, hi in LOCAL]
    m_contig = all(Ms[i][1] == Ms[i + 1][0] for i in range(len(Ms) - 1))
    q = lambda f: arb(fmpq(f.numerator, f.denominator))
    m_cover = bool(beta_of(q(Ms[0][0])) < arb(6) / 5 and beta_of(q(Ms[-1][1])) > 3)
    Bs = sorted((Fr(x['BLO']), Fr(x['BHI'])) for x in s['far'])
    b_cover = Bs[0][0] == Fr(6, 5) and Bs[-1][1] == 3 and all(Bs[i][1] == Bs[i + 1][0] for i in range(len(Bs) - 1))
    tot = s['totals']
    res.update(
        local_intervals=sum(x['local_intervals'] for x in res['local']),
        near_intervals=sum(x['near_intervals'] for x in res['local']),
        annulus_cells=sum(x['near_cells'] for x in res['local']),
        far_cells=sum(x['verified_cells'] for x in res['far']),
        far_unused=sum(x['unused'] for x in res['far']),
        M_contiguous=m_contig, M_covers_6_5_to_3=m_cover, beta_covers_6_5_to_3=b_cover,
        hashes_all_match=all(res['hashes_match'].values()), seconds=round(time.time() - t0))
    res['ok'] = bool(all(x['ok'] for x in res['local']) and all(x['ok'] for x in res['far']) and m_contig and m_cover
                     and b_cover and res['far_unused'] == 0 and res['local_intervals'] == tot['local_intervals']
                     and res['near_intervals'] == tot['near_intervals']
                     and res['far_cells'] == tot['far_cells'])
    (ROOT / 'verification' / 'cells.json').write_text(json.dumps(res, indent=1) + '\n')
    print('cells replay ok:', res['ok'], '; content hashes match the recorded run:', res['hashes_all_match'])
    return 0 if res['ok'] else 1


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('cmd', choices=['generate', 'replay', 'summary'])
    ap.add_argument('dir', nargs='?', default=os.environ.get('CELLS_DIR', str(ROOT / 'cells')))
    ap.add_argument('-j', '--jobs', type=int, default=1)
    a = ap.parse_args()
    d = Path(a.dir).absolute()
    if a.cmd == 'summary':
        SUMMARY.parent.mkdir(exist_ok=True)
        SUMMARY.write_text(json.dumps(summary(d), indent=1) + '\n'); print('wrote', SUMMARY.relative_to(ROOT))
    elif a.cmd == 'generate':
        generate(d, a.jobs)
    else:
        raise SystemExit(replay(d))
